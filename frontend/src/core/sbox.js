/**
 * 全表（DDT / LAT）内存上限，单位 = cell 数。
 *
 * 一个 S 盒的 DDT 是 `inSize × outSize` 的计数表。8bit 盒 = 256×256 = 65536（无压力）；
 * 但 16bit 盒 = 65536×65536 ≈ 4.3G cell（Uint16 也要 8GB）——建表直接崩。
 * 超过这个上限时**不再建全表**，改由 `analysis.js` 按需计算单行（精确、O(inSize)）。
 * 见「拼图」样例：三个 16×16 S 盒 + 一个 16→32 查找表都落在这条线下。
 */
export const SBOX_TABLE_CAP = 1 << 24;

/** 经典差分分布表 / 线性逼近表类的 S 盒分析对象 */
export class SBox {
  /**
   * @param {number[]} table  真值表，长度为 2^inBits
   * @param {number} inBits   输入位宽
   * @param {number} [outBits] 输出位宽，默认等于 inBits
   * @param {string} [name]
   */
  constructor(table, inBits, outBits = inBits, name = 'SBox') {
    this.table = table;
    this.inBits = inBits;
    this.outBits = outBits;
    this.name = name;
    this.inSize = 1 << inBits;
    // ⚠️ 缺陷修复（「拼图」样例暴露）：`1 << 32` 在 JS 里回绕成 **1**（`1 << 31` 变负数），
    //    于是输出位宽 ≥ 31 时 outSize 坍缩 → 下游 `for (b = 1; b < outSize; b++)` 一次都不跑，
    //    DDT/LAT 退化成全零、`bestTransition` 报 prob=0 —— 而同一张表的值级加密是**确定性**的，
    //    掩码级与值级自相矛盾。位宽 ≥ 31 时按实数算（2**32 = 4294967296）。
    this.outSize = outBits >= 31 ? 2 ** outBits : (1 << outBits);
    this.outMask = outBits >= 32 ? 0xFFFFFFFF : (1 << outBits) - 1;
    this._ddt = null;
    this._lat = null;
  }

  /** 全表（DDT/LAT）是否在内存上限内 —— false 时须走「按需单行」路径 */
  fullTableFeasible() {
    return this.inSize * this.outSize <= SBOX_TABLE_CAP;
  }

  static fromBuiltin(key) {
    const b = BUILTIN_SBOXES[key];
    if (!b) throw new Error(`未知内置 S 盒: ${key}`);
    const outBits = b.outputSize ?? b.size;
    return new SBox(b.table.slice(), b.size, outBits, b.name);
  }

  /** 应用 S 盒 */
  apply(x) {
    return this.table[x & (this.inSize - 1)];
  }

  /** 校验：是否为合法置换（非等宽一定不是；宽输出用 Set，避免 Uint8Array(2**32) 崩溃） */
  isValidPermutation() {
    if (this.inBits !== this.outBits) return false;
    const seen = new Set();
    for (const v of this.table) {
      if (v < 0 || v >= this.outSize || seen.has(v)) return false;
      seen.add(v);
    }
    return true;
  }

  /** 差分分布表 DDT[Δin][Δout] = #{x : S(x)^S(x^Δin) = Δout} */
  getDDT() {
    if (this._ddt) return this._ddt;
    if (!this.fullTableFeasible()) {
      throw new Error(
        `S 盒「${this.name}」(${this.inBits}→${this.outBits}) 的 DDT 为 `
        + `${this.inSize}×${this.outSize}，超出全表上限 ${SBOX_TABLE_CAP}；`
        + '请改用 analysis.js 的「按需单行」差分路径（ddtRowOnDemand），不要建全表。');
    }
    const n = this.inSize;
    const ddt = [];
    for (let a = 0; a < n; a++) ddt.push(new Uint16Array(this.outSize));
    for (let a = 0; a < n; a++) {
      for (let x = 0; x < n; x++) {
        const d = (this.table[x] ^ this.table[x ^ a]) & this.outMask;
        ddt[a][d]++;
      }
    }
    this._ddt = ddt;
    return ddt;
  }

  /**
   * 线性逼近表 LAT[a][b] = #{x : a·x = b·S(x)} - 2^(n-1)
   * 采用二维 Walsh-Hadamard 变换实现，O(n·2^n)
   * 由卷积定理：sum_x (-1)^{a·x ⊕ b·S(x)} = WHT2D(f)[a][b]
   * 其中 f 为联合分布计数数组，则 LAT[a][b] = WHT[a][b] / 2
   */
  getLAT() {
    if (this._lat) return this._lat;
    if (!this.fullTableFeasible()) {
      throw new Error(
        `S 盒「${this.name}」(${this.inBits}→${this.outBits}) 的 LAT 为 `
        + `${this.inSize}×${this.outSize}，超出全表上限 ${SBOX_TABLE_CAP}；`
        + '宽输出（≥ 31bit）的线性侧没有可行的精确算法，请显式标注「不支持」而不是给 0。');
    }
    const n = this.inSize;
    const m = this.outSize;
    const size = n * m;
    const f = new Int32Array(size);
    for (let x = 0; x < n; x++) {
      f[(x << this.outBits) | this.table[x]]++;
    }
    walsh2D(f, this.inBits, this.outBits);
    const lat = [];
    for (let a = 0; a < n; a++) {
      const row = new Int32Array(m);
      for (let b = 0; b < m; b++) {
        // WHT = 2 * #{a·x = b·S(x)} - 2^n，故 LAT = WHT / 2
        row[b] = f[(a << this.outBits) | b] >> 1;
      }
      lat.push(row);
    }
    this._lat = lat;
    return lat;
  }

  /** 差分均匀度（最大 DDT 非平凡值） */
  differentialUniformity() {
    const ddt = this.getDDT();
    let mx = 0, argA = 0, argB = 0;
    for (let a = 1; a < this.inSize; a++) {
      for (let b = 0; b < this.outSize; b++) {
        if (ddt[a][b] > mx) { mx = ddt[a][b]; argA = a; argB = b; }
      }
    }
    return { value: mx, inputDiff: argA, outputDiff: argB };
  }

  /** 线性度（最大 |LAT| 非平凡值） */
  linearity() {
    const lat = this.getLAT();
    let mx = 0, argA = 0, argB = 0;
    for (let a = 1; a < this.inSize; a++) {
      for (let b = 1; b < this.outSize; b++) {
        const v = Math.abs(lat[a][b]);
        if (v > mx) { mx = v; argA = a; argB = b; }
      }
    }
    return { value: mx, inputMask: argA, outputMask: argB };
  }

  /** 非线性度 = 2^(n-1) - 线性度 */
  nonlinearity() {
    return (1 << (this.inBits - 1)) - this.linearity().value;
  }

  /** 差分分支数 */
  diffBranchNumber() {
    let best = 1 << 30, argA = 1, argB = 1;
    for (let a = 1; a < this.inSize; a++) {
      for (let b = 1; b < this.outSize; b++) {
        if (this.getDDT()[a][b] > 0) {
          const w = hw(a) + hw(b);
          if (w < best) { best = w; argA = a; argB = b; }
        }
      }
    }
    return { value: best, inputDiff: argA, outputDiff: argB };
  }

  /**
   * 提取差分特征表：所有 DDT[a][b] > 0 的项，附概率
   * 用于后续差分路径搜索
   */
  diffTransitions() {
    const ddt = this.getDDT();
    const out = [];
    for (let a = 1; a < this.inSize; a++) {
      const row = [];
      for (let b = 0; b < this.outSize; b++) {
        if (ddt[a][b] > 0) {
          row.push({ a, b, count: ddt[a][b], prob: ddt[a][b] / this.inSize });
        }
      }
      out.push(row);
    }
    return out;
  }

  /** 提取线性特征表 */
  linTransitions() {
    const lat = this.getLAT();
    const out = [];
    for (let a = 1; a < this.inSize; a++) {
      const row = [];
      for (let b = 1; b < this.outSize; b++) {
        if (lat[a][b] !== 0) {
          const corr = lat[a][b] / (1 << (this.inBits - 1));
          row.push({ a, b, count: lat[a][b], corr, bias: corr / 2 });
        }
      }
      out.push(row);
    }
    return out;
  }

  /** 导出为 C 数组 / Python 列表格式 */
  exportCode(lang = 'c') {
    const hex = this.table.map(v => '0x' + v.toString(16).padStart(2, '0'));
    const name = this.name.replace(/[^A-Za-z0-9]/g, '_').toLowerCase();
    if (lang === 'python') {
      return `${name} = [\n    ${hex.join(', ')}\n]`;
    }
    if (lang === 'json') {
      return JSON.stringify({ name: this.name, size: this.inBits, outputSize: this.outBits, table: this.table });
    }
    const per = 16;
    let s = `static const uint8_t ${name}[${this.table.length}] = {\n`;
    for (let i = 0; i < hex.length; i += per) {
      s += '    ' + hex.slice(i, i + per).join(', ') + ',\n';
    }
    return s + '};';
  }
}

/** 二维 Walsh-Hadamard 变换（原地，按 inBits/outBits 拆分索引） */
function walsh2D(f, inBits, outBits) {
  const inSize = 1 << inBits, outSize = 1 << outBits;
  // 先对输出维变换
  for (let x = 0; x < inSize; x++) {
    const base = x << outBits;
    for (let len = 1; len < outSize; len <<= 1) {
      for (let i = 0; i < outSize; i += len << 1) {
        for (let j = 0; j < len; j++) {
          const u = f[base + i + j], v = f[base + i + j + len];
          f[base + i + j] = u + v;
          f[base + i + j + len] = u - v;
        }
      }
    }
  }
  // 再对输入维变换
  for (let len = 1; len < inSize; len <<= 1) {
    for (let i = 0; i < inSize; i += len << 1) {
      for (let j = 0; j < len; j++) {
        const b1 = (i + j) << outBits, b2 = (i + j + len) << outBits;
        for (let k = 0; k < outSize; k++) {
          const u = f[b1 + k], v = f[b2 + k];
          f[b1 + k] = u + v;
          f[b2 + k] = u - v;
        }
      }
    }
  }
}

function hw(x) {
  x = x >>> 0;
  x = x - ((x >>> 1) & 0x55555555);
  x = (x & 0x33333333) + ((x >>> 2) & 0x33333333);
  x = (x + (x >>> 4)) & 0x0F0F0F0F;
  return (x * 0x01010101) >>> 24;
}

/** 从十六进制/十进制文本解析 S 盒 */
export function parseSBoxText(text, inBits) {
  const tokens = text.split(/[^0-9a-fA-FxX]+/).filter(Boolean);
  const vals = [];
  for (const t of tokens) {
    let v;
    if (/^0[xX]/.test(t)) v = parseInt(t, 16);
    else if (/^[0-9a-fA-F]+$/.test(t) && /[a-fA-F]/.test(t)) v = parseInt(t, 16);
    else v = parseInt(t, 10);
    if (!Number.isNaN(v)) vals.push(v);
  }
  return vals;
}
