# ---------------------------------------------------------------------------
# BCA_Light —— 差分路径搜索后端
# ---------------------------------------------------------------------------
# BCA_Light 是 SAT 编码 + kissat 求解的差分/线性路径搜索引擎，源码在
# backend/bca_light（进 git）。调用链：
#
#     Django（跑在 WSL 里）──本地子进程──> python3 bca_entry.py ──stdin/stdout JSON──> BCA
#
# 三条硬约束，改这里之前先读：
#
# 1. **BCA 只能在 Linux 里跑**。bca/solver.py 用 ctypes 调 libc 的
#    PR_SET_PDEATHSIG 防孤儿进程（Linux 专属），kissat 也是 ELF 二进制。
#    所以 Django 必须在 WSL 里跑；Windows 侧的 Django 会看到 bca.status()
#    报 unavailable（前端据此显示"后端未启用"，不影响其他功能）。
# 2. **不跨 wsl.exe**。那条边界上本项目实测撞过 5 类故障（僵尸 VM、UTF-16LE
#    编码、/mnt/c 路径转换、SIGTERM 掐断、沙箱拦程序）。Django 搬进 WSL 后，
#    这里就只是本地进程调用，那一整类风险直接消失。
# 3. **BCA_DIR 用项目内那份**（WSL 里经 /mnt/c 访问）。同一个目录，不存在
#    "改了没同步"的问题；config.json 里的 solver.path 是这台机器的绝对路径，
#    换机器不必改文件 —— 设环境变量 BCA_KISSAT 覆盖（优先级最高），或把
#    solver.path 写成裸名 kissat，让它走 PATH、再兜底项目自带副本。
#    解析只在 bca/config.py:resolve_solver_path 一处实现。
#
# 可用环境变量覆盖，方便换机器或临时指向别处的 BCA 副本。

# BCA_Light 根目录（含 main.py / bca_entry.py / config.json / data/）
